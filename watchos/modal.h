#pragma once
#include "input.h"   // InputEvent

// ───── Модальный диалог: общий каркас для всплывающих окон/меню ─────
// Раньше каждый диалог дублировал у себя «дождаться отпускания пальца + inputBegin»,
// цикл «inputPoll + powerNoteActivity + delay» и пару fillRoundRect/drawRoundRect.
// Эти три примитива убирают копипасту; поведение прежнее.

// Открыть модальный диалог: дождаться отпускания пальца (которым его вызвали, чтобы
// его release не «нажал» элемент под окном), затем начать слушать ввод (inputBegin).
void modalBegin();

// Один опрос ввода внутри модального цикла. Сам отмечает активность (сброс таймера
// сна) и троттлит CPU в простое (~20мс). Возврат — событие; для EVT_TAP заполняет x/y.
InputEvent modalPoll(int16_t &x, int16_t &y);

// Затенить весь экран «вуалью» (дешёвый дизеринг чёрными линиями через строку, ~50%):
// альфа-блендинга на этом дисплее нет (read-back пикселей не поддерживается). Идемпотентно.
// Обычно звать НЕ нужно — `modalPanel` затеняет фон сам. Вызывай напрямую лишь для
// полноэкранного меню БЕЗ панели, где затенение нужно вручную.
void modalScrim();

// Нарисовать панель окна: СНАЧАЛА затеняет фон (modalScrim), затем заливка фоном + рамка
// цветом border со скруглением r. Контент окна рисуешь поверх — он попадает на чистую панель.
void modalPanel(int x, int y, int w, int h, int r, uint16_t border);
