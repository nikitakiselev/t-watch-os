// Модальная экранная T9-клавиатура (мультитап). Блокирующий ввод: рисует себя
// на весь экран, крутит свой цикл опроса тача/кнопки. Тап по клавише циклирует
// её символы; пауза/другая клавиша фиксируют. < — стереть, OK — подтвердить,
// aA — регистр, долгое нажатие кнопки — отмена.
//
// Возвращает true и заполняет out, если нажали OK; false при отмене.
// Вызывающий после возврата должен перерисовать свой экран (клавиатура затирает всё).
bool keyboardPrompt(const char *title, char *out, int outLen);
