#pragma once
#include "config.h"

// Обёртка над TTGOClass: единая точка инициализации железа и доступа к нему.
// Глобальные указатели определены в hw.cpp.
extern TTGOClass *watch;   // экземпляр часов
extern TFT_eSPI  *tft;     // дисплей (принадлежит watch)

// Инициализация: питание (AXP202), дисплей (ST7789), подсветка, RTC, кнопка.
void hwBegin();

// Заряд батареи в процентах (0..100).
int  hwBattPercent();

// ─────────────────────────── Яркость дисплея (общая, на всю ОС) ───────────
// Уровень подсветки 0..255, хранится в NVS и применяется при старте/пробуждении.
// hwSetBrightness клампит к минимуму (экран не гаснет в ноль) и сохраняет.
void    hwSetBrightness(uint8_t level);
uint8_t hwBrightness();

// Короткий импульс вибромотора (тактильный отклик на нажатие). Неблокирующий:
// мотор гаснет сам через ms. Первый вызов лениво инициализирует мотор.
void    hwVibrate(int ms);

// Текущее время RTC (базовый пояс — MSK).
RTC_Date hwNow();

// Синхронизировать RTC по NTP (интернет). Требует уже поднятого Wi-Fi.
// Блокирует до timeoutMs. true — успех (RTC выставлен в MSK). Wi-Fi не трогает.
bool hwNtpSync(uint32_t timeoutMs);

// Перевести время RTC в нужный пояс по смещению в минутах.
// Возвращает часы/минуты/секунды этого пояса (с переносом через сутки).
void hwTimeInZone(const RTC_Date &base, int offsetMin, int &h, int &m, int &s);

// ─────────────────────────── Акселерометр (BMA423) ───────────────────────
// Конфигурация + включение датчика (±2g, 100 Hz). Идемпотентно — можно звать
// при каждом входе в приложение; реальная настройка выполняется один раз.
void hwAccelBegin();

// Сырые оси датчика. false — чтение не удалось. hwAccelBegin() вызывается сам.
bool hwAccelRead(int16_t &x, int16_t &y, int16_t &z);

// Перевод сырых осей в систему координат ЭКРАНА (оси BMA423 на T-Watch 2020 V3
// повёрнуты на 90°). Результат нормирован на |g| в [-1..1]:
//   sx > 0 — опущен ПРАВЫЙ край, sy > 0 — опущен НИЗ экрана.
void hwAccelToScreen(int16_t x, int16_t y, int16_t z, float &sx, float &sy);

// Текущая ориентация по осям экрана. Возвращает одну из строк:
//   "FACE UP" / "FACE DOWN" / "TOP DN" / "BOTTOM DN" / "LEFT DN" / "RIGHT DN".
const char *hwAccelDirection(int16_t x, int16_t y, int16_t z);

// ─────────────────────────── Шагомер (аппаратный, BMA423) ────────────────
// BMA423 считает шаги в собственном железе — продолжает считать даже когда
// ESP32 в light sleep (датчик питается отдельно от CPU). hwStepBegin включает
// фичу (идемпотентно). Счётчик обнуляется при перезагрузке ESP32 (re-init BMA)
// и по hwStepReset().
void     hwStepBegin();
uint32_t hwStepCount();    // накопленные шаги с момента включения/сброса
void     hwStepReset();    // обнулить аппаратный счётчик
