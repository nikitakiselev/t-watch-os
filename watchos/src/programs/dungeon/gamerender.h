#pragma once
#include <stdint.h>

// Геометрия вьюпорта.
// Тайл на экране 32px = ровно ×2 от нативного 16px → пиксели не «гуляют». Вьюпорт 7×7 = 224×224.
// Под HUD доступно 240×216; вьюпорт ставится в (8,24) и нижний ряд обрезается кромкой экрана,
// чтобы карта занимала всю доступную высоту (без пустой полосы снизу).
#define SRC_PX 16          // нативный размер тайла в спрайтах
#define TILE   32          // размер тайла на экране (×2, целое — без дробного масштаба)
#define VW     7           // ширина вьюпорта в клетках
#define VH     7           // высота (7-й ряд частично за нижней кромкой)
#define MAP_X  8           // центрируем 224 в 240
#define MAP_Y  24          // под HUD
#define ARROW_OFF 18       // отступ центра стрелки от грани карты

void gameRenderInit();                  // создать off-screen спрайт карты
void gameRenderFree();                  // освободить
// Нарисовать вьюпорт (игрок в центре). ox/oy — пиксельный сдвиг мира для плавного
// скролла: рисуется на один ряд/столбец тайлов больше, чтобы заезжающий из-за края
// тайл был покрыт. По умолчанию (0,0) — обычный статичный кадр.
void gameRenderMap(int32_t px, int32_t py, int ox = 0, int oy = 0);
// Анимация игрока: режим (бег/простой) + направление взгляда (dx<0 влево, >0 вправо, 0 — без изменения).
void gamePlayerSetMoving(bool moving, int dx);
void gamePlayerAnimAdvance();           // продвинуть кадр текущей анимации (idle/run)
