#pragma once
#include "input.h"

// Переиспользуемая навигация по списку: свайп ↑/↓ двигает выбор (с прокруткой окна).
// Отрисовку строк и реакцию на тап экран делает сам — здесь только состояние выбора.
struct ListNav {
    int count;   // всего элементов
    int vis;     // сколько строк видно (для прокрутки); <=0 — без прокрутки
    int sel;     // выбранный индекс
    int top;     // верхний видимый индекс (смещение прокрутки)
};

// Обработать EVT_UP/EVT_DOWN: сдвинуть sel (кламп) и подстроить top под окно vis.
// Возвращает true, если sel/top изменились (нужна перерисовка).
bool listNavEvent(ListNav &l, InputEvent e);
